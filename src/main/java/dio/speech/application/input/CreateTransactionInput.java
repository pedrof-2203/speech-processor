package dio.speech.application.input;

import dio.speech.domain.Category;
import dio.speech.domain.PaymentMethod;
import dio.speech.domain.Type;
import org.springframework.ai.tool.annotation.ToolParam;

import java.math.BigDecimal;

public record CreateTransactionInput(
        @ToolParam(description = "User's input containing the transaction's description.")
        String input,

        @ToolParam(description = "The response generated by the Chat Model.")
        String output,

        @ToolParam(description = "The transaction's amount.")
        BigDecimal amount,

        @ToolParam(description = "The transaction's category.")
        Category category,

        @ToolParam(description = "The type of the transaction.")
        Type type,

        @ToolParam(description = "The payment method of the transaction.")
        PaymentMethod paymentMethod
) {
}
